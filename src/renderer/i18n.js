export const DICTS = { en, es };
export const LANGUAGES = [['en', 'English'], ['es', 'Español']];

let lang = 'en';
export const getLang = () => lang;
export function setLang(l) {
  lang = DICTS[l] ? l : 'en';
  document.documentElement.lang = lang;
}
/** Formato de números según el idioma (26,000 / 26.000). */
export const fmt = (n) => Number(n).toLocaleString(lang === 'es' ? 'es-ES' : 'en-US');

export function t(key, params) {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
  return s;
}

/** Traduce los textos fijos del HTML: data-i18n (texto) y data-i18n-<atributo>. */
export function translateDom(root = document) {
  for (const el of root.querySelectorAll('*')) {
    for (const { name, value } of [...el.attributes]) {
      if (name === 'data-i18n') el.textContent = t(value);
      else if (name.startsWith('data-i18n-')) el.setAttribute(name.slice(10), t(value));
    }
  }
}
